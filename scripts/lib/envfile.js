// Tiny .env reader/writer shared by the helper scripts (no dependencies).
function parseEnv(text) {
  const out = {};
  const clean = String(text || '').replace(/^\uFEFF/, '');
  for (const raw of clean.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const i = line.indexOf('=');
    if (i < 1) continue;
    const key = line.slice(0, i).trim();
    let value = line.slice(i + 1).trim();
    const quoted = /^(["']).*\1$/.test(value);
    if (!quoted) {
      const hash = value.search(/\s#/);
      if (hash !== -1) value = value.slice(0, hash).trim();
    } else {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function isPlaceholder(value) {
  return !value || /replace_with|PASTE|YOUR_|changeme|placeholder/i.test(value);
}

// Settings the setup script does not ask about but must never delete when it re-writes backend/.env.
const KEEP_KEYS = [
  'DB_SSL', 'FRONTEND_URL', 'GITHUB_OAUTH_REDIRECT_URI',
  'SMTP_HOST', 'SMTP_PORT', 'SMTP_SECURE', 'SMTP_USER', 'SMTP_PASS', 'MAIL_FROM',
  'AUTO_MIGRATE', 'AUTH_RATE_LIMIT', 'FORGOT_RATE_LIMIT',
];

function renderBackendEnv(v) {
  const extras = KEEP_KEYS.filter((k) => v[k]).map((k) => `${k}=${v[k]}`);
  const extraBlock = extras.length ? `\n# ---------- Other settings (kept when you run npm run setup again) ----------\n${extras.join('\n')}\n` : '';
  return `# Generated by "npm run setup". Safe to edit; restart the backend after changes.
# ---------- Server ----------
PORT=${v.PORT}
NODE_ENV=${v.NODE_ENV}

# ---------- Database (PostgreSQL, e.g. Neon) ----------
DATABASE_URL=${v.DATABASE_URL}

# ---------- Secrets ----------
JWT_SECRET=${v.JWT_SECRET}
JWT_EXPIRES_IN=${v.JWT_EXPIRES_IN}
# Encrypts users' GitHub tokens in the database. Changing it logs everyone out of GitHub.
TOKEN_ENC_KEY=${v.TOKEN_ENC_KEY}
# Must be identical to the GitHub Actions secret SCAN_SECRET in the scanner repository.
SCAN_SECRET=${v.SCAN_SECRET}

# ---------- Frontend (comma separated; https://*.vercel.app is allowed) ----------
FRONTEND_ORIGIN=${v.FRONTEND_ORIGIN}

# ---------- Scanner workflow (the GitHub repository that holds .github/workflows/scan-repository.yml) ----------
SCANNER_REPO=${v.SCANNER_REPO}
SCANNER_REPO_REF=${v.SCANNER_REPO_REF}
# Fine-grained token with "Actions: Read and write" on SCANNER_REPO
SCANNER_REPO_TOKEN=${v.SCANNER_REPO_TOKEN}

# ---------- GitHub OAuth (optional - users can paste a personal access token instead) ----------
GITHUB_CLIENT_ID=${v.GITHUB_CLIENT_ID}
GITHUB_CLIENT_SECRET=${v.GITHUB_CLIENT_SECRET}
${extraBlock}`;
}

module.exports = { parseEnv, isPlaceholder, renderBackendEnv, KEEP_KEYS };
